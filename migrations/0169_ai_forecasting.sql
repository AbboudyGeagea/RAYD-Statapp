-- Migration 0169: Report AI forecasts with Prophet + a sequential correction (operator, 2026-11-18).
-- *** LAUMC BRANCH ONLY ***
--
-- The operator: "the linear regression is not AI to be relied on, specially on trends that change
-- weekly (weekdays vs weekends) or holiday periods (Christmas and Ramadan)". Measured on production
-- (2019-2026, scripts/sql/ai_trend_export.sql): Saturdays run at 35 % of a weekday, Sundays 24 %,
-- holidays and both Eids close like a Sunday, Dec 24 and 31 are half days, Ramadan itself changes
-- nothing. Backtest of 14 cut-offs x 90 days: the straight line missed daily volume by 67 %,
-- Prophet with this calendar by 15 %, Prophet + a correction learnt from its own recent errors had
-- the best next-day error (14.0 %). utils/forecasting.py trains it every night, the page reads what
-- it stored.
--
-- ai_calendar        holidays and closures, editable on the Report AI page (settings capability).
--                    One list for both hospitals (utils/site_db.SHARED_TABLES): national holidays.
--                      closure    the hospital closes (a Sunday-like day)
--                      half_day   Christmas Eve, New Year's Eve
--                      no_effect  listed but worked (Ashura, Prophet's Birthday, Annunciation since 2025)
--                      event      a period left out of training (COVID, war, protests)
--                    Seed: Lebanon's official holidays 2019-2028, corrected from the data for the
--                    years seen (the days each Eid really closed, holidays moved to the Monday,
--                    Easter Mondays, 2 Dec 2025); later Eid dates are estimates to check.
-- ai_forecast        the latest forecast per series (volume, device:<AE>, storage), one row a day
-- ai_forecast_run    how each series was trained, and what the page explains (JSONB info)
-- ai_forecast_check  each forecast day, once it happened: what the model said the night before and
--                    what came (the next-day error shown on the page)

CREATE TABLE IF NOT EXISTS public.ai_calendar (
    id          SERIAL PRIMARY KEY,
    start_date  DATE NOT NULL,
    end_date    DATE NOT NULL,
    name        TEXT NOT NULL,
    kind        TEXT NOT NULL CHECK (kind IN ('closure', 'half_day', 'no_effect', 'event')),
    source      TEXT NOT NULL DEFAULT 'seed' CHECK (source IN ('seed', 'user')),
    created_by  TEXT,
    created_at  TIMESTAMP NOT NULL DEFAULT now(),
    CHECK (end_date >= start_date),
    UNIQUE (start_date, name)
);

CREATE TABLE IF NOT EXISTS public.ai_forecast (
    series_key  TEXT NOT NULL,
    ds          DATE NOT NULL,
    yhat        DOUBLE PRECISION NOT NULL,
    yhat_lower  DOUBLE PRECISION,
    yhat_upper  DOUBLE PRECISION,
    PRIMARY KEY (series_key, ds)
);

CREATE TABLE IF NOT EXISTS public.ai_forecast_run (
    series_key    TEXT PRIMARY KEY,
    model         TEXT NOT NULL,
    trained_from  DATE,
    trained_to    DATE,
    run_at        TIMESTAMP NOT NULL DEFAULT now(),
    info          JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE IF NOT EXISTS public.ai_forecast_check (
    series_key  TEXT NOT NULL,
    ds          DATE NOT NULL,
    forecast    DOUBLE PRECISION NOT NULL,
    actual      DOUBLE PRECISION NOT NULL,
    made_on     DATE NOT NULL,
    PRIMARY KEY (series_key, ds)
);

